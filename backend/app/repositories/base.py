"""Contrato de acesso a dados. Mock e SQLite (Gold real) implementam os mesmos métodos,
então services/routers não mudam quando a camada Gold ficar pronta."""
from __future__ import annotations

from typing import Protocol


class Repository(Protocol):
    # catálogos
    def competencias(self) -> list[str]: ...
    def municipios_bairros(self) -> dict[str, list[str]]: ...
    def classes(self) -> dict[str, str]: ...
    def alimentadores(self, municipio: str | None = None) -> list[dict]: ...
    # dashboard: A5 por mês; A3 por mês x município x bairro x classe.
    # Intervalo inclusivo, ordem crescente; [] significa ausência de registros.
    # Bairro exige município. Tabela indisponível levanta NaoDisponivelNaGold.
    def kpis_mensais(self, inicio: str, fim: str) -> list[dict]: ...
    def segmentos_mensais(self, inicio: str, fim: str, municipio: str | None = None, bairro: str | None = None, classe: str | None = None) -> list[dict]: ...
    # receita: UCs com GD no fim do período atual e o volume dessas mesmas UCs nos dois períodos (A2).
    # {qtd_ucs, energia_base_kwh, energia_atual_kwh}; None quando a A2 não foi exportada (é complementar à A3).
    def gd_mesmas_ucs(self, base_inicio: str, base_fim: str, atual_inicio: str, atual_fim: str, municipio: str | None = None, bairro: str | None = None, classe: str | None = None) -> dict | None: ...
    # faturamento / consumo
    def faturas(self, inicio: str, fim: str, municipio: str | None = None, bairro: str | None = None, classe: str | None = None) -> list[dict]: ...
    # unidades consumidoras
    def buscar_ucs(self, q: str | None, municipio: str | None, classe: str | None, limite: int) -> list[dict]: ...
    def uc(self, uc_id: str) -> dict | None: ...
    def consumo_uc(self, uc_id: str) -> list[dict]: ...  # [{competencia, consumo_kwh}]
    def faturas_uc(self, uc_id: str) -> list[dict]: ...
    def pagina_faturas_uc(self, uc_id: str, aba: str, ano: int | None, situacao: str, pagina: int) -> dict: ...
    def medidor_uc(self, uc_id: str) -> dict | None: ...
    def trocas_medidor_uc(self, uc_id: str) -> list[dict]: ...
    def gd_uc(self, uc_id: str) -> dict | None: ...
    def atendimentos_uc(self, uc_id: str) -> list[dict]: ...
    def atendimentos_mensais(self, inicio: str, fim: str, municipio: str | None = None) -> list[dict]: ...  # [{mes_referencia, qtd_atendimentos, qtd_avaliacoes, soma_notas}]
    # rede
    def ocorrencias(self, inicio: str, fim: str, alimentador_id: str | None = None, municipio: str | None = None, uc_id: str | None = None) -> list[dict]: ...
    def indicadores_continuidade(self, inicio: str, fim: str, alimentador_id: str | None = None, municipio: str | None = None) -> list[dict]: ...
    def ucs_afetadas_por_alimentador(self, inicio: str, fim: str, municipio: str | None = None) -> dict[str, int]: ...
    # Por local da UC: nivel "municipio" ou "bairro" (bairro sempre com o município).
    def interrupcoes_por_local(self, inicio: str, fim: str, nivel: str, alimentador_id: str | None = None, municipio: str | None = None) -> list[dict]: ...  # [{municipio, bairro, qtd, minutos, ucs_afetadas}]
    def ucs_por_local(self, nivel: str, alimentador_id: str | None = None, municipio: str | None = None) -> dict[tuple, int]: ...  # {(municipio, bairro|None): qtd}
    def causas_interrupcao(self, inicio: str, fim: str, alimentador_id: str | None = None, municipio: str | None = None) -> list[dict]: ...  # [{causa, causa_evitavel, qtd, minutos}]
    # perdas
    def suspeitas(self) -> list[dict]: ...
    def criar_ordem(self, dados: dict) -> dict: ...
    def listar_ordens(self, status: str | None = None) -> list[dict]: ...
    def obter_ordem(self, ordem_id: int) -> dict | None: ...
    def atualizar_ordem(self, ordem_id: int, campos: dict) -> dict: ...


class OrdensStore(Protocol):
    """Onde as ordens de inspeção ficam guardadas. Tabela do PORTAL (não da Gold): ver ordens_store.py.
    Os métodos de ordens do Repository (mock ou SQLite/Gold) delegam para este armazém."""
    def criar(self, dados: dict) -> dict: ...
    def listar(self, status: str | None = None) -> list[dict]: ...
    def obter(self, ordem_id: int) -> dict | None: ...
    def atualizar(self, ordem_id: int, campos: dict) -> dict: ...
